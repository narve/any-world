const LABELS: Record<string, Record<string, string>> = { nb: NB };

/** the label of a library tag in `lang` (the tag itself when there is none) */
export function tagLabel(tag: string, lang: string): string {
  return LABELS[baseLanguage(lang)]?.[tag] ?? tag;
}

/** tags that have a label in `lang` (for tests) */
export function labelledTags(lang: string): string[] {
  return Object.keys(LABELS[baseLanguage(lang)] ?? {});
}
