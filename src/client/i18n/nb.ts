/**
 * Norsk bokmål UI catalog (DESIGN §7b). Same keys and params as en.ts; tests/i18n/nb.test.ts
 * fails on a missing or extra key, a param that is not in the English template, or a template that
 * does not parse.
 *
 * House style:
 * - Short, plain game-UI bokmål. Buttons are imperatives ("Plukk opp", "Snakk med …", "Lukk").
 * - Quotes are «…», dashes are – (with spaces), percent is "40 %".
 * - Genre words come from the world as params ({conflict}, {hp}, {defeated}, {currency}…) and are
 *   already in the world's language. They can be any gender and number, so templates avoid
 *   agreeing with them (no "din/ditt {hp}", no "{resource} er tom/tomt"); a colon or a
 *   parenthesis is used instead.
 * - Engine log lines keep the world-authored verb as is: "{attacker|cap} {verb} {target}" works in
 *   Norwegian because the verb is a present-tense form ("biter", "innvender mot").
 * - "Turn" is "runde"; a whole playthrough ("run") is "spill"/"forsøk".
 */
